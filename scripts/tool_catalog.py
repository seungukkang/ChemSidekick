"""Print a Markdown catalog of all registered tools, ordered by tool ID.

    uv run python scripts/tool_catalog.py              # print to the terminal
    uv run python scripts/tool_catalog.py --write PATH # write to a file

The catalog is generated from the registry, so it is always in sync with
the code. Category codes are defined in chemsidekick/core/registry.py.
"""

import argparse
from pathlib import Path

from chemsidekick import __version__
from chemsidekick.core.registry import CATEGORIES, discover


def catalog() -> str:
    registry = discover()
    lines = [
        "# Tool catalog",
        "",
        f"Generated by `scripts/tool_catalog.py` from chemsidekick {__version__}. "
        "Do not edit by hand.",
        "",
        "## Categories",
        "",
        "| Code | Category | Title | Tools |",
        "|---|---|---|---|",
    ]
    groups = registry.by_category()
    for key, cat in CATEGORIES.items():
        lines.append(f"| {cat.code} | `{key}` | {cat.title} | {len(groups.get(key, []))} |")
    lines += [
        "",
        "## Tools",
        "",
        "| ID | Command | Title | Resources | Requires | Summary |",
        "|---|---|---|---|---|---|",
    ]
    for s in registry.all():
        requires = ", ".join(s.requires) or "—"
        lines.append(
            f"| {s.id} | `csk {s.name}` | {s.title} | {s.resources} | {requires} | {s.summary} |"
        )
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", type=Path, help="write the catalog to this file")
    args = parser.parse_args()
    text = catalog()
    if args.write:
        args.write.write_text(text, encoding="utf-8")
        print(f"wrote {args.write}")
    else:
        print(text, end="")
